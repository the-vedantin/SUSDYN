"""Engine (powertrain) curve — the ONE source of the car's torque/power.

The curve is produced by the 1dFVEngineSolver, a 1-D finite-volume gas-dynamics
engine simulator by Sun Devil Motorsports (SDM26, Arizona State University FSAE),
MIT licensed — https://github.com/NIXELFi/1dFVEngineSolver.  Vahan does not
recompute engine physics; it reads the solver's converged sweep (see
data/engine_curve_sdm26.json, regenerated by the sweep driver) and hands the
crank-torque table to the lap simulator and every dynamics consumer.

Honesty: the solver is SIMULATED, not dyno-validated.  Its trends are reliable
and its shape is physical, but the absolute level is approximate — anchor it to
a measured dyno pull when one exists (see anchor_curve_to_dyno).

Credits — Suspension & VD: Yu, Cougar Racing.  Powertrain: Sun Devil Motorsports.
"""
from __future__ import annotations
import json
import os
from typing import List, Optional, Tuple

_HERE = os.path.dirname(__file__)
_CURVE_JSON = os.path.join(_HERE, "data", "engine_curve_sdm26.json")
_SWEEP_JSON = os.path.join(_HERE, "data", "engine_sweep_sdm26.json")

# ── Calibration inputs (ALL explicit — these are the knobs, not magic) ──────
# The raw solver under-reads ~2x: its breathing (VE) caps at ~0.57-0.71 where a
# real race 600 runs ~0.85-0.95, and its friction (FMEP) reads 2.6-5.4 bar
# where realistic sportbike friction is ~1.3-2.7 bar.  Verified 2026-08:
# even UNRESTRICTED the raw solver makes 48 hp vs ~110 real — a calibration
# floor, not an input problem.  Two correction methods, both defensible:
#   'corrected' — per-rpm physics correction: scale indicated work by
#                 (VE_TARGET / VE_sim), subtract a realistic friction line.
#   'anchored'  — keep the raw curve SHAPE, scale so peak power equals a
#                 published restricted-CBR600RR level.
#   'raw'       — the uncorrected solver output (for reference only).
VE_TARGET = 0.88            # realistic race-600 breathing (dyno-typical 0.85-0.95)
# Real VE FALLS at high rpm (the restrictor's pressure drop grows steeply as
# flow approaches choke, plus port velocity limits) — a flat target would put
# peak power at the redline, which no restricted 600 does.  Explicit taper:
VE_FALL_START_RPM = 9500.0  # VE holds VE_TARGET up to here…
VE_AT_13K = 0.72            # …then falls linearly to this at 13,000 rpm
FMEP_A_BAR = 0.10           # friction line: FMEP[bar] = A + B*(rpm/1000)
FMEP_B_BAR = 0.20           #   -> 1.3 bar @6k, 2.2 @10.5k, 2.7 @13k (Heywood-class)
ANCHOR_HP = 80.0            # published restricted-CBR600RR crank peak (75-85 typical)
DISPLACEMENT_M3 = 599e-6    # CBR600RR
DEFAULT_METHOD = "corrected"

METHOD_LABELS = {
    "raw": "SDM26 1-D sim RAW (known ~2x low — reference only)",
    "corrected": (f"SDM26 corrected: VE→{VE_TARGET:.2f} + realistic friction "
                  f"({FMEP_A_BAR:.2f}+{FMEP_B_BAR:.2f}·rpm/1000 bar)"),
    "anchored": f"SDM26 shape anchored to published {ANCHOR_HP:.0f} hp crank",
}

# Watermark / attribution strings (used by the GUI, binder and figures).
CREDIT_SUSPENSION = "Suspension & VD: Yu — Cougar Racing"
CREDIT_POWERTRAIN = ("Powertrain: Sun Devil Motorsports (SDM26) — "
                     "1dFVEngineSolver, MIT")
ENGINE_LABEL = "SDM26 1-D sim (Sun Devil Motorsports) — NOT dyno-validated"


def _load() -> Optional[dict]:
    try:
        with open(_CURVE_JSON, "r") as f:
            return json.load(f)
    except (OSError, ValueError):
        return None


def _load_sweep() -> Optional[dict]:
    try:
        with open(_SWEEP_JSON, "r") as f:
            return json.load(f)
    except (OSError, ValueError):
        return None


def fmep_real_bar(rpm: float, a: float = FMEP_A_BAR, b: float = FMEP_B_BAR) -> float:
    """Realistic sportbike friction line (bar). Explicit input, not hidden."""
    return a + b * float(rpm) / 1000.0


def ve_target_curve(rpm, ve_peak: float = VE_TARGET,
                    fall_start: float = VE_FALL_START_RPM,
                    ve_13k: float = VE_AT_13K):
    """Target breathing vs rpm: flat ve_peak to fall_start, then linear to
    ve_13k at 13,000 (restrictor starvation).  All three knobs explicit.

    The defaults are the module constants AS DEFINED (Python binds them at
    import); callers with a different calibration MUST pass fall_start /
    ve_13k explicitly.  Mutating VE_FALL_START_RPM / VE_AT_13K at run time
    does nothing here — that was the dead Engine-page taper controls bug
    (audit 2026-09-22 item 21)."""
    import numpy as np
    r = np.asarray(rpm, float)
    frac = np.clip((r - fall_start) / max(13000.0 - fall_start, 1.0), 0.0, 1.0)
    return ve_peak + (ve_13k - ve_peak) * frac


def apply_power_cap(rpm, torque_Nm, cap_hp):
    """Crank torque limited so power <= cap_hp (T = min(T, P_cap/omega)).
    Applied at USE time — a saved table is never rewritten.  The curve is
    resampled (original points + a 100 rpm grid) so the knee where the cap
    starts is not lost between table points.  cap_hp None/<=0 = no cap."""
    import numpy as np
    r = np.asarray(rpm, float); t = np.asarray(torque_Nm, float)
    if cap_hp is None or not np.isfinite(float(cap_hp)) or float(cap_hp) <= 0 or r.size < 2:
        return list(r), list(t)
    P = float(cap_hp) * 745.7
    if np.max(t * r * 2 * np.pi / 60.0) <= P:
        return list(r), list(t)                     # cap never reached
    g = np.unique(np.r_[r, np.arange(np.ceil(r[0] / 100) * 100, r[-1], 100.0)])
    tg = np.interp(g, r, t)
    tg = np.minimum(tg, P / np.maximum(g * 2 * np.pi / 60.0, 1e-6))
    return list(g), list(tg)


def engine_tables_from_car(car) -> dict:
    """Named crank-torque tables the project carries:
    car['engine_tables'] = {key: {'label', 'source', 'table': [[rpm, N·m]]}}.
    The old single car['engine_table'] (+ engine_table_label) is kept as one
    option ('engine_table') for backward compatibility."""
    car = car or {}
    out = {}
    for k, v in (car.get('engine_tables') or {}).items():
        if isinstance(v, dict) and v.get('table') and len(v['table']) >= 2:
            out[str(k)] = v
    if car.get('engine_table') and 'engine_table' not in out:
        out['engine_table'] = {'label': car.get('engine_table_label') or 'project torque table',
                               'source': 'car.engine_table (older single-table form)',
                               'table': car['engine_table']}
    return out


def car_engine_curve(car):
    """THE engine curve for a project car dict — the one source for the
    Engine page, the Laptime page and the lap engine window:
    engine_method (+ calibration knobs), engine_table_choice among
    engine_tables, and engine_power_cap_hp (user input; 0/None = off)."""
    car = car or {}
    tabs = engine_tables_from_car(car)
    choice = car.get('engine_table_choice')
    if choice not in tabs:
        choice = next(iter(tabs), None)
    tab = tabs.get(choice) if choice else None
    cap = car.get('engine_power_cap_hp')
    return engine_curve(
        car.get('engine_method', DEFAULT_METHOD),
        ve_target=float(car.get('engine_ve_target', VE_TARGET)),
        ve_fall_rpm=float(car.get('engine_ve_fall_rpm', VE_FALL_START_RPM)),
        ve_13k=float(car.get('engine_ve_13k', VE_AT_13K)),
        fmep_a=float(car.get('engine_fmep_a', FMEP_A_BAR)),
        fmep_b=float(car.get('engine_fmep_b', FMEP_B_BAR)),
        anchor_hp=float(car.get('engine_anchor_hp', ANCHOR_HP)),
        table=tab['table'] if tab else None,
        table_label=tab.get('label') if tab else None,
        power_cap_hp=float(cap) if cap not in (None, '') else None)


def engine_curve(method: str = DEFAULT_METHOD, ve_target: float = VE_TARGET,
                 fmep_a: float = FMEP_A_BAR, fmep_b: float = FMEP_B_BAR,
                 anchor_hp: float = ANCHOR_HP,
                 ve_fall_rpm: float = VE_FALL_START_RPM,
                 ve_13k: float = VE_AT_13K,
                 table=None, table_label: str | None = None,
                 power_cap_hp: float | None = None):
    """_engine_curve_raw, then the power cap (if any) applied at use time."""
    c = _engine_curve_raw(method, ve_target=ve_target, fmep_a=fmep_a, fmep_b=fmep_b,
                          anchor_hp=anchor_hp, ve_fall_rpm=ve_fall_rpm, ve_13k=ve_13k,
                          table=table, table_label=table_label)
    if c is None or power_cap_hp is None or float(power_cap_hp) <= 0:
        return c
    r, t = apply_power_cap(c[0], c[1], power_cap_hp)
    lbl = c[2] if len(r) == len(c[0]) and list(r) == list(c[0]) and list(t) == list(c[1])         else f"{c[2]}, capped at {float(power_cap_hp):g} hp"
    return r, t, lbl


def _engine_curve_raw(method: str = DEFAULT_METHOD, ve_target: float = VE_TARGET,
                      fmep_a: float = FMEP_A_BAR, fmep_b: float = FMEP_B_BAR,
                      anchor_hp: float = ANCHOR_HP,
                      ve_fall_rpm: float = VE_FALL_START_RPM,
                      ve_13k: float = VE_AT_13K,
                      table=None, table_label: str | None = None):
    """(rpm[], crank torque N·m[], label) for the chosen calibration method.

    'table'    : a named crank-torque table saved in the project (see
                 engine_tables_from_car), e.g. the powertrain team's curve —
                 used as given; falls back to DEFAULT_METHOD when no table.

    ALL SIX calibration knobs are explicit arguments (ve_target, ve_fall_rpm,
    ve_13k, fmep_a, fmep_b, anchor_hp) — no module globals are read at call
    time, so two windows / cars can never leak a calibration into each other.

    'corrected': per-rpm — IMEP scaled by (ve_target / VE_sim(rpm)), then a
                 realistic friction line subtracted.  torque = BMEP·Vd/(4π).
    'anchored' : raw curve scaled so peak crank power = anchor_hp.
    'raw'      : untouched solver output.
    Returns None if the data files are missing."""
    import numpy as np
    method = str(method).lower()
    if method == "table":
        if table is not None and len(table) >= 2:
            pts = sorted((float(a), float(b)) for a, b in table)
            return ([p[0] for p in pts], [p[1] for p in pts],
                    str(table_label or "project torque table"))
        method = DEFAULT_METHOD
    sw = _load_sweep()
    if sw and sw.get("curve") and method in ("corrected", "raw"):
        rpm = np.array([p["rpm"] for p in sw["curve"]], float)
        if method == "raw":
            tq = np.array([p["brake_torque_Nm"] for p in sw["curve"]], float)
            return list(rpm), list(tq), METHOD_LABELS["raw"]
        imep = np.array([p["imep_bar"] for p in sw["curve"]], float)
        ve = np.array([p["ve_atm"] for p in sw["curve"]], float)
        ve_t = ve_target_curve(rpm, ve_peak=float(ve_target),
                               fall_start=float(ve_fall_rpm),
                               ve_13k=float(ve_13k))
        imep_c = imep * (ve_t / np.maximum(ve, 1e-3))
        bmep_c = imep_c - (float(fmep_a) + float(fmep_b) * rpm / 1000.0)
        bmep_c = np.maximum(bmep_c, 0.0)
        tq = bmep_c * 1e5 * DISPLACEMENT_M3 / (4 * np.pi)
        lbl = (f"SDM26 corrected: VE→{float(ve_target):.2f} + friction "
               f"{float(fmep_a):.2f}+{float(fmep_b):.2f}·rpm/1000 bar")
        return list(rpm), list(tq), lbl
    # anchored (or corrected-fallback when sweep file missing): use raw curve
    d = _load()
    if not d or not d.get("curve"):
        return None
    rpm = [float(p["rpm"]) for p in d["curve"]]
    tq = [float(p["brake_torque_Nm"]) for p in d["curve"]]
    if len(rpm) < 2:
        return None
    if method == "anchored":
        tq = anchor_curve_to_dyno(rpm, tq, float(anchor_hp))
        return rpm, tq, f"SDM26 shape anchored to {float(anchor_hp):.0f} hp crank"
    return rpm, tq, ENGINE_LABEL


def sdm26_engine_curve() -> Optional[Tuple[List[float], List[float], str]]:
    """(rpm[], crank torque N·m[], label) — the DEFAULT engine for the whole
    tool (backbone).  Now returns the CALIBRATED curve (DEFAULT_METHOD);
    the raw solver curve is available via engine_curve('raw')."""
    c = engine_curve(DEFAULT_METHOD)
    if c is not None:
        return c
    d = _load()
    if not d or not d.get("curve"):
        return None
    rpm = [float(p["rpm"]) for p in d["curve"]]
    tq = [float(p["brake_torque_Nm"]) for p in d["curve"]]
    if len(rpm) < 2:
        return None
    return rpm, tq, ENGINE_LABEL


def sdm26_peaks() -> Optional[dict]:
    """{'peak_power':{rpm,hp}, 'peak_torque':{rpm,Nm}} or None."""
    d = _load()
    if not d:
        return None
    return {"peak_power": d.get("peak_power"), "peak_torque": d.get("peak_torque")}


def anchor_curve_to_dyno(rpm, torque_Nm, dyno_peak_power_hp: float):
    """Scale a simulated crank-torque curve so its PEAK POWER matches a measured
    dyno figure, preserving the solver's SHAPE.  Use the day a real restricted-
    engine dyno number exists; until then the raw sim curve stands.

    Returns a new torque list scaled by (dyno_peak_hp / sim_peak_hp)."""
    import numpy as np
    r = np.asarray(rpm, float)
    t = np.asarray(torque_Nm, float)
    p_hp = t * r * 2 * np.pi / 60.0 / 745.7   # crank power at each point (hp)
    sim_peak = float(p_hp.max())
    if sim_peak <= 0:
        return list(t)
    return list(t * (float(dyno_peak_power_hp) / sim_peak))
